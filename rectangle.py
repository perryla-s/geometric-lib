def area(a, b):
    '''
    Принимает стороны прямоугольника и возвращает площадь.

    Параметры:
            a (int/float): первая сторона прямоугольника.
            b (int/float): вторая сторона прямоугольника.

    Возвращаемое значение: (int/float) площадь прямоугольника.

    Пример вызова:
        area(3, 4)
        12
    '''
    return a * b


def perimeter(a, b):
    '''
    Принимает стороны прямоугольника и возвращает периметр.

    Параметры:
            a (int/float): первая сторона прямоугольника.
            b (int/float): вторая сторона прямоугольника.

    Возвращаемое значение: (int/float) периметр прямоугольника.

    Пример вызова:
        perimeter(3, 4)
        14
    '''
    return (a + b) * 2