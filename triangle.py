def area(a, h):
    '''
    Принимает сторону треугольника и высоту, опущенную на нее, и возвращает площадь.

    Параметры:
        a (int/float): сторона треугольника (основание).
        h (int/float): высота, опущенная на сторону a.

    Возвращаемое значение: (float) площадь треугольника.

    Пример вызова:
        area(10, 5)
        25.0
    '''
    return a * h / 2


def perimeter(a, b, c):
    '''
    Принимает стороны треугольника и возвращает периметр.

    Параметры:
        a (int/float): первая сторона треугольника.
        b (int/float): вторая сторона треугольника.
        c (int/float): третья сторона треугольника.

    Возвращаемое значение: (int/float) периметр треугольника.

    Пример вызова:
        perimeter(3, 4, 5)
        12
    '''
    return a + b + c