def area(a):
    '''
    Принимает сторону квадрата и возвращает площадь.

    Параметр:
        a (int/float): сторона квадрата.

    Возвращаемое значение: (int/float) площадь квадрата.

    Пример вызова:
        area(5)
        25
    '''
    return a * a


